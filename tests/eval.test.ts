/**
 * m_evaltest_* / ag_evaltest_* namespace — distinct from both `m_demo_*`
 * (DUK-11's real demo data) and from the "eval" namespace `bun run eval`
 * uses for a real replay report, so this test file, a manual `bun run
 * eval`, and every other test file's fixtures can never collide. See
 * src/eval/provision.ts's module doc for the full isolation rationale.
 */
const NAMESPACE = "evaltest";
const EVAL_TEST_MERCHANT_IDS = ["m_evaltest_kirana", "m_evaltest_electronics"];

async function wipeEvalTestData(): Promise<void> {
  await query("DELETE FROM audit_events WHERE merchant_id = ANY($1::text[])", [
    EVAL_TEST_MERCHANT_IDS,
  ]);
  await query("DELETE FROM merchants WHERE id = ANY($1::text[])", [
    EVAL_TEST_MERCHANT_IDS,
  ]);
}

beforeAll(wipeEvalTestData);
afterAll(wipeEvalTestData);

/** Strips ids/timestamps/latency so two replays of the same transcript can be compared for decision equality. */
function normalizeStep(step: ReplayStepResult) {
  return {
    decision: step.outcome.decision,
    rule: step.outcome.rule,
    reason_code: step.audit.reason_code,
    amount_paise: step.audit.amount_paise,
  };
}

describe("dataset generation (pure, offline, no Postgres)", () => {
  test("bun run eval:generate is byte-identical across two runs", () => {
    const first = JSON.stringify(buildFrozenDataset());
    const second = JSON.stringify(buildFrozenDataset());
    expect(first).toBe(second);
  });

  test("every transcript carries a valid origin, and both authors are present", () => {
    const dataset = buildFrozenDataset();
    expect(dataset.length).toBeGreaterThan(0);
    expect(dataset.every((t) => ORIGINS.includes(t.origin))).toBe(true);
    // Both halves must exist. A corpus that silently lost the independently
    // generated batch would still pass every other assertion here while
    // quietly reverting the report's strongest claim to self-agreement.
    expect(dataset.some((t) => t.origin === "hand")).toBe(true);
    expect(dataset.some((t) => t.origin === "llm")).toBe(true);
  });

  test("~200 sessions, 70/30 benign to adversarial, 60/40 train to held-out", () => {
    const dataset = buildFrozenDataset();
    // Exact totals moved once an independently generated batch joined the
    // corpus, and they will move again if it is regenerated. The invariant is
    // the benign-to-adversarial ratio, not a magic number: the hand batch is
    // 140/60 by construction and the generated batch is asked for the same
    // shape, so the pooled ratio must stay near 70/30.
    expect(dataset.length).toBeGreaterThanOrEqual(200);

    const benign = dataset.filter((t) => t.attack_class === null).length;
    const adversarial = dataset.length - benign;
    expect(benign + adversarial).toBe(dataset.length);
    expect(benign / dataset.length).toBeGreaterThan(0.6);
    expect(benign / dataset.length).toBeLessThan(0.8);

    const train = dataset.filter((t) => t.split === "train").length;
    const holdout = dataset.filter((t) => t.split === "holdout").length;
    expect(train + holdout).toBe(dataset.length);
    // Not an exact 120/80: the split is stratified per class, so each stratum
    // rounds independently (84 benign + 7 x 5 classes = 119). The ratio is the
    // requirement; the exact integer was always incidental. One transcript of
    // slack per stratum is the most rounding can cost.
    const target = Math.round(dataset.length * TRAIN_FRACTION);
    expect(Math.abs(train - target)).toBeLessThanOrEqual(
      ATTACK_CLASSES.length + 1
    );
  });

  test("the COMMITTED fixture matches what the generator currently produces", () => {
    // The gap this closes: every other test here calls buildFrozenDataset()
    // directly, so all 184 could pass while fixtures/eval/transcripts.json on
    // disk was generated by older code. That happened — the stratification key
    // changed from class to (origin, class) and the fixture was never
    // regenerated, leaving a committed split of 144/97 against a generated
    // 143/98. Two different "frozen" splits is not a frozen split, and DUK-20
    // scores the held-out half exactly once.
    //
    // tests/eval-llm.test.ts already compares a committed file against its
    // builder for the generator prompt; this applies the same check to the
    // dataset, which is the artefact the published numbers actually rest on.
    const committed = JSON.parse(
      readFileSync(
        join(import.meta.dir, "..", "fixtures", "eval", "transcripts.json"),
        "utf8"
      )
    ) as unknown;
    expect(JSON.stringify(committed)).toBe(
      JSON.stringify(buildFrozenDataset())
    );
  });

  test("the split is STRATIFIED: every attack class gets the same holdout share", () => {
    // Regression for the first frozen dataset, which pooled all 200 transcripts
    // into one shuffle and left category_laundering with 1 holdout instance and
    // stale_price with 2. A per-rule line reading "1 of 1 caught" cannot support
    // the reporting plan, which deliberately quotes raw integers precisely
    // because the per-class denominators are small.
    const dataset = buildFrozenDataset();
    const holdoutCounts = ATTACK_CLASSES.map(
      (c) =>
        dataset.filter((t) => t.attack_class === c && t.split === "holdout")
          .length
    );
    // Uniformity ACROSS classes no longer holds, and must not be enforced: the
    // generated batch chose its own class mix, and normalising that would mean
    // discarding or duplicating what an independent author actually produced.
    // What still has to hold is that no class is starved below the point where
    // a raw "N of M" line means anything.
    for (const n of holdoutCounts) expect(n).toBeGreaterThanOrEqual(4);

    // Within the HAND batch, which is uniform by construction at 12 per class,
    // uniformity is still the right assertion — it catches a regression to the
    // pooled shuffle that this test was originally written for.
    const handHoldout = ATTACK_CLASSES.map(
      (c) =>
        dataset.filter(
          (t) =>
            t.attack_class === c && t.origin === "hand" && t.split === "holdout"
        ).length
    );
    expect(
      Math.max(...handHoldout) - Math.min(...handHoldout)
    ).toBeLessThanOrEqual(1);
  });

  test("each of the five adversarial classes has sessions in BOTH splits", () => {
    const dataset = buildFrozenDataset();
    for (const attackClass of ATTACK_CLASSES) {
      const inClass = dataset.filter((t) => t.attack_class === attackClass);
      expect(inClass.length).toBeGreaterThan(0);
      expect(inClass.some((t) => t.split === "train")).toBe(true);
      expect(inClass.some((t) => t.split === "holdout")).toBe(true);
    }
  });

  test("every transcript id is unique", () => {
    const dataset = buildFrozenDataset();
    expect(new Set(dataset.map((t) => t.id)).size).toBe(dataset.length);
  });
});

describe("near-boundary benign fixtures (pure, offline, no Postgres)", () => {
  /** Mirrors src/gate/index.ts's `totalAssertedPaise`, kept local to this
   * test file rather than imported from src/eval/report.ts (out of scope
   * for this ticket) or src/gate/index.ts (never imported by the test suite
   * that verifies fixtures against it). */
  function totalPaise(
    items: readonly { quantity: number; asserted_price_paise: number }[]
  ): number {
    return items.reduce(
      (sum, item) => sum + item.quantity * item.asserted_price_paise,
      0
    );
  }

  const nearBoundary = generateNearBoundaryBenignTranscripts();
  const snapshots = loadCatalogSnapshots();

  test("27 near-boundary sessions exist, all labelled benign", () => {
    expect(nearBoundary.length).toBe(27);
    expect(nearBoundary.every((t) => t.attack_class === null)).toBe(true);
    expect(nearBoundary.every((t) => t.expected_tripped_rule === null)).toBe(
      true
    );
    expect(nearBoundary.every((t) => t.origin === "hand")).toBe(true);
  });

  test("near-boundary sessions are a meaningful share (10-30%) of the benign population", () => {
    const dataset = buildFrozenDataset();
    // transcriptGroup(), not a raw attack_class === null check: DUK-30 Gap 2
    // added 20 interrupted-intent transcripts that also carry
    // attack_class: null, and they are deliberately NOT part of the benign
    // population this share is measured against.
    const benignCount = dataset.filter(
      (t) => transcriptGroup(t) === "benign"
    ).length;
    // Was a hardcoded 140; the benign population grew when the generated
    // batch added its own benign sessions.
    expect(benignCount).toBeGreaterThanOrEqual(140);
    const share = nearBoundary.length / benignCount;
    expect(share).toBeGreaterThan(0.15);
    expect(share).toBeLessThan(0.3);
  });

  test("near_cap sessions: cumulative spend is strictly under the real spend cap, every round at/under the real approval threshold", () => {
    const nearCap = nearBoundary.filter((t) =>
      t.id.startsWith("hand-benign-nearcap-")
    );
    expect(nearCap.length).toBe(5);
    for (const transcript of nearCap) {
      const policy = snapshots[transcript.merchant].policy;
      let cumulative = 0;
      for (const step of transcript.steps) {
        const amount = totalPaise(step.items);
        expect(amount).toBeLessThanOrEqual(policy.approval_threshold_paise);
        cumulative += amount;
      }
      expect(cumulative).toBeLessThan(policy.spend_cap_paise);
      expect(cumulative / policy.spend_cap_paise).toBeGreaterThanOrEqual(0.75);
    }
  });

  test("near_threshold sessions: the single order is at/under the real approval threshold", () => {
    const nearThreshold = nearBoundary.filter((t) =>
      t.id.startsWith("hand-benign-nearthreshold-")
    );
    expect(nearThreshold.length).toBe(12);
    for (const transcript of nearThreshold) {
      const policy = snapshots[transcript.merchant].policy;
      expect(transcript.steps.length).toBe(1);
      const amount = totalPaise(transcript.steps[0]!.items);
      expect(amount).toBeLessThanOrEqual(policy.approval_threshold_paise);
      expect(amount / policy.approval_threshold_paise).toBeGreaterThanOrEqual(
        0.85
      );
    }
  });

  test("ambiguous_category sessions: every line item's real category is allowed, and sku-a22 (personal-care) never appears", () => {
    const ambiguous = nearBoundary.filter((t) =>
      t.id.startsWith("hand-benign-ambiguous-")
    );
    expect(ambiguous.length).toBe(6);
    const kirana = snapshots.kirana;

    for (const transcript of ambiguous) {
      expect(transcript.merchant).toBe("kirana");
      const items = transcript.steps[0]!.items;
      expect(totalPaise(items)).toBeLessThanOrEqual(
        kirana.policy.approval_threshold_paise
      );
      for (const item of items) {
        expect(item.item_id).not.toBe("sku-a22");
        const product = kirana.productsById.get(item.item_id);
        if (product === undefined) {
          throw new Error(`unknown item ${item.item_id} in ${transcript.id}`);
        }
        expect(kirana.policy.category_allowlist).toContain(product.category);
      }
    }

    // Anchors the "ambiguity" claim in real seed data: sku-a22 genuinely
    // exists, is genuinely "personal-care", and is genuinely off the
    // allowlist — the fact these baskets are near a real category boundary.
    const a22 = kirana.productsById.get("sku-a22");
    if (a22 === undefined)
      throw new Error("sku-a22 missing from kirana catalog");
    expect(a22.category).toBe("personal-care");
    expect(kirana.policy.category_allowlist).not.toContain(a22.category);
  });

  test("at_stock sessions: sku-a10 is ordered for exactly its real remaining stock", () => {
    const atStock = nearBoundary.filter((t) =>
      t.id.startsWith("hand-benign-atstock-")
    );
    expect(atStock.length).toBe(4);
    const a10 = snapshots.kirana.productsById.get("sku-a10");
    if (a10 === undefined)
      throw new Error("sku-a10 missing from kirana catalog");
    expect(a10.stock).toBe(4);

    for (const transcript of atStock) {
      const items = transcript.steps[0]!.items;
      const a10Line = items.find((i) => i.item_id === "sku-a10");
      if (a10Line === undefined) {
        throw new Error(`${transcript.id} has no sku-a10 line item`);
      }
      expect(a10Line.quantity).toBe(a10.stock);
      expect(totalPaise(items)).toBeLessThanOrEqual(
        snapshots.kirana.policy.approval_threshold_paise
      );
    }
  });

  test("near-boundary session ids land in BOTH the train and holdout splits", () => {
    const dataset = buildFrozenDataset();
    const nearBoundaryIds = new Set(nearBoundary.map((t) => t.id));
    const inSplit = dataset.filter((t) => nearBoundaryIds.has(t.id));
    expect(inSplit.length).toBe(nearBoundary.length);
    expect(inSplit.some((t) => t.split === "train")).toBe(true);
    expect(inSplit.some((t) => t.split === "holdout")).toBe(true);
  });
});

describe("interrupted-intent fixtures (pure, offline, no Postgres)", () => {
  const interruptedIntent = generateInterruptedIntentTranscripts();

  test("20 interrupted-intent sessions exist, carrying expected_step_decisions instead of attack_class", () => {
    expect(interruptedIntent.length).toBe(20);
    expect(interruptedIntent.every((t) => t.attack_class === null)).toBe(true);
    expect(
      interruptedIntent.every((t) => t.expected_tripped_rule === null)
    ).toBe(true);
    expect(
      interruptedIntent.every((t) => t.expected_step_decisions !== undefined)
    ).toBe(true);
    expect(interruptedIntent.every((t) => t.origin === "hand")).toBe(true);
  });

  test("category_substitute and stock_substitute sessions declare block-then-allow; threshold_no_substitute declares a lone escalate", () => {
    const withSubstitute = interruptedIntent.filter(
      (t) =>
        t.id.startsWith("interrupted-category-") ||
        t.id.startsWith("interrupted-stock-")
    );
    expect(withSubstitute.length).toBe(14);
    for (const t of withSubstitute) {
      expect(t.expected_step_decisions).toEqual(["block", "allow"]);
      expect(t.steps.length).toBe(2);
    }

    const noSubstitute = interruptedIntent.filter((t) =>
      t.id.startsWith("interrupted-threshold-")
    );
    expect(noSubstitute.length).toBe(6);
    for (const t of noSubstitute) {
      expect(t.expected_step_decisions).toEqual(["escalate"]);
      expect(t.steps.length).toBe(1);
    }
  });

  test("category_substitute: the blocked item's real category is off the allowlist, the substitute's is on it", () => {
    const snapshots = loadCatalogSnapshots();
    const categorySubstitute = interruptedIntent.filter((t) =>
      t.id.startsWith("interrupted-category-")
    );
    expect(categorySubstitute.length).toBe(8);
    for (const t of categorySubstitute) {
      const policy = snapshots[t.merchant].policy;
      const blockedItem = t.steps[0]!.items[0]!;
      const subItem = t.steps[1]!.items[0]!;
      const blockedProduct = snapshots[t.merchant].productsById.get(
        blockedItem.item_id
      )!;
      const subProduct = snapshots[t.merchant].productsById.get(
        subItem.item_id
      )!;
      expect(policy.category_allowlist).not.toContain(blockedProduct.category);
      expect(policy.category_allowlist).toContain(subProduct.category);
    }
  });

  test("stock_substitute: the blocked item's requested quantity genuinely exceeds real stock", () => {
    const snapshots = loadCatalogSnapshots();
    const stockSubstitute = interruptedIntent.filter((t) =>
      t.id.startsWith("interrupted-stock-")
    );
    expect(stockSubstitute.length).toBe(6);
    for (const t of stockSubstitute) {
      const blockedItem = t.steps[0]!.items[0]!;
      const blockedProduct = snapshots[t.merchant].productsById.get(
        blockedItem.item_id
      )!;
      expect(blockedItem.quantity).toBeGreaterThan(blockedProduct.stock);
      expect(blockedItem.asserted_price_paise).toBe(blockedProduct.price_paise);
    }
  });

  test("threshold_no_substitute: the single order genuinely exceeds the real approval threshold, and stays under the real cap", () => {
    const snapshots = loadCatalogSnapshots();
    const noSubstitute = interruptedIntent.filter((t) =>
      t.id.startsWith("interrupted-threshold-")
    );
    for (const t of noSubstitute) {
      const policy = snapshots[t.merchant].policy;
      const item = t.steps[0]!.items[0]!;
      const amount = item.quantity * item.asserted_price_paise;
      expect(amount).toBeGreaterThan(policy.approval_threshold_paise);
      expect(amount).toBeLessThanOrEqual(policy.spend_cap_paise);
    }
  });

  test("interrupted-intent is its own stratum: at least 4 holdout instances, present in both splits", () => {
    const dataset = buildFrozenDataset();
    const interruptedIntentIds = new Set(interruptedIntent.map((t) => t.id));
    const inDataset = dataset.filter((t) => interruptedIntentIds.has(t.id));
    expect(inDataset.length).toBe(interruptedIntent.length);
    const holdout = inDataset.filter((t) => t.split === "holdout");
    const train = inDataset.filter((t) => t.split === "train");
    expect(holdout.length).toBeGreaterThanOrEqual(4);
    expect(train.length).toBeGreaterThan(0);

    // Not merged into the "benign" stratum: transcriptGroup() must resolve
    // every one of these to its own bucket, never "benign".
    expect(
      inDataset.every((t) => transcriptGroup(t) === "interrupted_intent")
    ).toBe(true);
  });
});

describe("replay against the real gate (Postgres, eval-namespaced, no network)", () => {
  let merchantIds: EvalMerchantIds;
  const dataset = buildFrozenDataset();

  beforeAll(async () => {
    merchantIds = await resetEvalMerchants(NAMESPACE);
  });

  test("replaying one transcript twice yields identical decisions", async () => {
    const transcript = dataset.find((t) => t.id === "hand-budget_split-01");
    if (transcript === undefined)
      throw new Error("fixture hand-budget_split-01 not found");

    const first = await replayTranscript(NAMESPACE, merchantIds, transcript);
    const firstDecisions = first.steps.map(normalizeStep);

    // Reset between replays: the SAME agent_id is reused (transcripts are
    // deterministic on their own id), so without wiping, the second
    // replay's spend cap would see the first replay's own orders as prior
    // spend and diverge — that would be testing leftover state, not
    // decide()'s determinism.
    merchantIds = await resetEvalMerchants(NAMESPACE);
    const second = await replayTranscript(NAMESPACE, merchantIds, transcript);
    const secondDecisions = second.steps.map(normalizeStep);

    expect(secondDecisions).toEqual(firstDecisions);
    expect(firstDecisions[firstDecisions.length - 1]?.rule).toBe("SPEND_CAP");
  });

  test("one representative transcript per adversarial class trips its expected rule", async () => {
    merchantIds = await resetEvalMerchants(NAMESPACE);
    for (const attackClass of ATTACK_CLASSES) {
      const transcript = dataset.find((t) => t.attack_class === attackClass);
      if (transcript === undefined)
        throw new Error(`no fixture for class ${attackClass}`);
      const expectedRule = transcript.expected_tripped_rule;
      if (expectedRule === null)
        throw new Error(`${transcript.id} has no expected_tripped_rule`);

      const result = await replayTranscript(NAMESPACE, merchantIds, transcript);
      const lastStep = result.steps[result.steps.length - 1];
      if (lastStep === undefined)
        throw new Error(`${transcript.id} replayed with zero steps`);

      expect(lastStep.outcome.decision).not.toBe("allow");
      expect(lastStep.outcome.rule).toBe(expectedRule);
    }
  });

  test("a sample of benign transcripts always ALLOW", async () => {
    merchantIds = await resetEvalMerchants(NAMESPACE);
    const benignSample = dataset
      .filter((t) => t.attack_class === null)
      .slice(0, 8);
    for (const transcript of benignSample) {
      const result = await replayTranscript(NAMESPACE, merchantIds, transcript);
      expect(result.steps.every((s) => s.outcome.decision === "allow")).toBe(
        true
      );
    }
  });

  test("every near-boundary benign session ALLOWs at every step against the real gate", async () => {
    merchantIds = await resetEvalMerchants(NAMESPACE);
    const nearBoundaryIds = new Set(
      generateNearBoundaryBenignTranscripts().map((t) => t.id)
    );
    const nearBoundaryInDataset = dataset.filter((t) =>
      nearBoundaryIds.has(t.id)
    );
    expect(nearBoundaryInDataset.length).toBe(27);

    for (const transcript of nearBoundaryInDataset) {
      const result = await replayTranscript(NAMESPACE, merchantIds, transcript);
      expect(result.steps.every((s) => s.outcome.decision === "allow")).toBe(
        true
      );
    }
  }, 30_000);

  test("the full frozen dataset replays with a 100% catch/allow rate", async () => {
    merchantIds = await resetEvalMerchants(NAMESPACE);
    const results = await replayBatch<SplitTranscript>(
      NAMESPACE,
      merchantIds,
      dataset
    );
    const verdicts = results.map((r) => scoreReplay(r));
    const missed = verdicts.filter((v) => !v.caught);

    expect(missed.map((v) => v.transcript.id)).toEqual([]);

    const rows = summarizeBySplit(verdicts);
    for (const row of rows) {
      expect(row.rate).toBe(1);
    }
  }, 30_000);
});
