/**
 * The eval suite's single source of truth for what a "session transcript"
 * is. Everything else in src/eval/ — the hand-scripted attacks, the benign
 * generator, the runner, the metrics — is written against these types and
 * nothing else, which is what makes the LLM-backed half of DUK-18
 * pluggable later without touching any of them. See `TranscriptSource`
 * below for the exact seam.
 *
 * A transcript is one agent's checkout activity, expressed as `LineItem`
 * arrays exactly as the gate's `CheckoutRequest` consumes them — no
 * translation layer between "what the eval authored" and "what decide()
 * sees". Reuses `LineItem` and `GateRule` from shared/contracts.ts rather
 * than redeclaring parallel shapes.
 */
import type { Decision, GateRule, LineItem } from "../shared/contracts";

/**
 * 'hand' — authored by whoever wrote the gate's rules (this ticket).
 * 'llm'  — generated by a separate model call that never saw the gate
 *          implementation (the other half of DUK-18, not built here — see
 *          TranscriptSource below). Keeping this on every transcript is
 *          what lets the README state honestly which attacks share an
 *          author with the rules and which don't (projectmem #0010).
 */
export const ORIGINS = ["hand", "llm"] as const;
export type Origin = (typeof ORIGINS)[number];

export const ATTACK_CLASSES = [
  "budget_split",
  "threshold_straddling",
  "stale_price",
  "merchant_misclaim",
  "category_laundering",
] as const;
export type AttackClass = (typeof ATTACK_CLASSES)[number];

/**
 * Logical merchant the transcript targets. The runner maps these onto real,
 * eval-namespaced merchant ids provisioned from the actual DUK-11 demo
 * fixtures (fixtures/demo-merchant-{a,b}.csv/.policy.json) — see
 * src/eval/provision.ts. Kept as a closed union here (not a raw string) so
 * a typo in a hand-authored transcript fails typecheck instead of silently
 * resolving to nothing at replay time.
 */
export const EVAL_MERCHANTS = ["kirana", "electronics"] as const;
export type EvalMerchant = (typeof EVAL_MERCHANTS)[number];

/**
 * One `checkout` tool call. `session_id` is logical (namespaced by the
 * runner into a real `sessions.id`) and lives on the STEP, not the
 * transcript, because budget-split evasion is specifically the case where
 * one agent spans several fresh sessions within a single transcript — the
 * gate's spend cap must catch that regardless (see src/gate/index.ts's
 * CAP SCOPE note). Every other class happens to use one session per
 * transcript, but the type does not privilege that shape.
 */
export interface TranscriptStep {
  readonly session_id: string;
  readonly items: readonly LineItem[];
  /** Why this step exists — read by a human auditing the fixture, not by the runner. */
  readonly note: string;
}

/**
 * One agent's transcript: a logical agent id (namespaced by the runner into
 * a real `agents.id`) and its ordered checkout steps.
 *
 * `expected_tripped_rule`: null for a benign transcript, meaning every step
 * is expected to ALLOW. For an adversarial transcript, the GateRule its
 * LAST step is designed to trip — earlier steps are expected to ALLOW (or,
 * for threshold_straddling, sit at/under the threshold and still ALLOW)
 * and exist only to build the state the last step needs. This is ground
 * truth for src/eval/metrics.ts's catch-rate computation; it is not read
 * by the gate or the runner's replay logic, only by scoring.
 */
export interface Transcript {
  readonly id: string;
  readonly origin: Origin;
  readonly attack_class: AttackClass | null;
  readonly merchant: EvalMerchant;
  readonly agent_id: string;
  readonly steps: readonly TranscriptStep[];
  readonly expected_tripped_rule: GateRule | null;
  /**
   * Per-step expected decision, present ONLY on interrupted-intent transcripts.
   * A legitimate session whose first step is correctly stopped and whose later
   * step completes a substitute purchase is neither benign (which expects every
   * step to ALLOW) nor adversarial (which names an attack_class it does not
   * deserve). This field is how it declares its own shape.
   */
  readonly expected_step_decisions?: readonly Decision[];
}

/**
 * The reporting/stratification bucket a transcript belongs to: its
 * `attack_class` when it has one, `"interrupted_intent"` for a session
 * carrying `expected_step_decisions` (see the field's doc above), or
 * `"benign"` otherwise. Centralised here so dataset.ts's split
 * stratification and metrics.ts's per-group scoring can never drift apart
 * on what counts as which bucket — interrupted-intent transcripts have
 * `attack_class: null` just like true benign ones, so any keying logic
 * that only checks `attack_class` would silently merge the two.
 */
export function transcriptGroup(t: Transcript): string {
  if (t.attack_class !== null) return t.attack_class;
  if (t.expected_step_decisions !== undefined) return "interrupted_intent";
  return "benign";
}

export const TRAIN_SPLITS = ["train", "holdout"] as const;
export type Split = (typeof TRAIN_SPLITS)[number];

/** A transcript plus its frozen train/held-out assignment. */
export interface SplitTranscript extends Transcript {
  readonly split: Split;
}

/**
 * THE SEAM. A `TranscriptSource` is anything that can hand back a batch of
 * transcripts for a given seed. `src/eval/hand-attacks.ts` +
 * `src/eval/benign.ts`, composed in `src/eval/dataset.ts`, are the only
 * implementation today (`origin: 'hand'`).
 *
 * A later ticket adding the LLM-backed half implements this SAME interface
 * — e.g. `src/eval/llm-source.ts` exporting a `TranscriptSource` whose
 * `generate` calls the Anthropic API with the MCP tool schema and the
 * merchant's policy JSON (and nothing else — no view of the gate) and
 * returns `Transcript[]` with `origin: 'llm'`. Neither the runner
 * (src/eval/runner.ts) nor the metrics (src/eval/metrics.ts) import
 * anything from that module or switch on `origin`; they consume
 * `Transcript[]` regardless of who produced it. Composing both sources
 * (e.g. concatenating their output before the split) is the only wiring
 * a future ticket needs to add.
 */
export interface TranscriptSource {
  readonly origin: Origin;
  generate(seed: number): readonly Transcript[];
}
